/// Размеры компонентов приложения.
///
/// Компактные значения — интерфейс не должен быть раздутым.
class AppSizes {
  const AppSizes._();

  /// Высота обычной кнопки.
  static const double buttonHeight = 40;

  /// Высота большой кнопки.
  static const double buttonHeightLg = 48;

  /// Высота маленькой кнопки.
  static const double buttonHeightSm = 32;

  /// Высота поля ввода.
  static const double inputHeight = 44;

  /// Высота chip.
  static const double chipHeight = 30;

  /// Размер круглой icon button.
  static const double iconButtonSize = 36;

  /// Размер иконки в AppBar action.
  static const double appBarIconSize = 22;

  /// Размер обычной иконки.
  static const double iconSize = 20;

  /// Размер маленькой иконки.
  static const double iconSizeSm = 16;

  /// Размер большой иконки.
  static const double iconSizeLg = 28;

  /// Размер аватара S.
  static const double avatarSm = 28;

  /// Размер аватара M.
  static const double avatarMd = 40;

  /// Размер аватара L.
  static const double avatarLg = 64;

  // --- Bottom Navigation ---

  /// Высота floating bottom bar.
  static const double bottomBarHeight = 64;

  /// Размер иконки в bottom bar.
  static const double bottomBarIconSize = 24;

  /// Внутренний горизонтальный padding bottom bar.
  static const double bottomBarPadding = 8;
}
